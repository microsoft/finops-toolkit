BeforeDiscovery {
    $root = (Get-Item -Path $PSScriptRoot).Parent.Parent.Parent.Parent.FullName
    $commands = Get-ChildItem -Path (Join-Path $root 'src/powershell/Public') -Filter '*-FinOps*.ps1' -File |
        Where-Object { $_.BaseName -ne 'Start-FinOpsMultitool' } |
        ForEach-Object { @{ Name = $_.BaseName } }
}

BeforeAll {
    $root = (Get-Item -Path $PSScriptRoot).Parent.Parent.Parent.Parent.FullName
    $docsPath = Join-Path $root 'docs-mslearn/toolkit/powershell'
}

# Run `./src/scripts/Build-Documentation` to generate missing pages
Describe 'PowerShell command docs' {
    It 'Should have a docs page for <Name>' -ForEach $commands {
        $page = Get-ChildItem -Path $docsPath -Recurse -Filter "$($Name.ToLower()).md" -File
        $page | Should -Not -BeNullOrEmpty -Because "every public command needs a page generated by Build-Documentation"
        @($page).Count | Should -Be 1 -Because "each command should have exactly one docs page"
    }

    It 'Should list <Name> in powershell-commands.md' -ForEach $commands {
        (Get-Content (Join-Path $docsPath 'powershell-commands.md') -Raw) | Should -Match "\[$Name\]"
    }
}

Describe 'PowerShell command docs drift' {
    It 'Should match what Build-Documentation generates' {
        $files = Get-ChildItem -Path $docsPath -Recurse -Filter '*.md' -File
        $before = @{}
        foreach ($f in $files) { $before[$f.FullName] = Get-Content $f.FullName -Raw }
        # Normalize line endings: Windows checkouts may use CRLF while the generator writes LF
        $norm = { param($t) ($t -replace "`r`n", "`n") }
        try
        {
            & (Join-Path $root 'src/scripts/Build-Documentation.ps1') *> $null
            $after = Get-ChildItem -Path $docsPath -Recurse -Filter '*.md' -File
            $changed = @($after | Where-Object { -not $before.ContainsKey($_.FullName) -or (& $norm $before[$_.FullName]) -ne (& $norm (Get-Content $_.FullName -Raw)) } | ForEach-Object Name)
        }
        finally
        {
            # Restore original content and remove any newly generated pages
            Get-ChildItem -Path $docsPath -Recurse -Filter '*.md' -File | Where-Object { -not $before.ContainsKey($_.FullName) } | Remove-Item
            foreach ($k in $before.Keys) { Set-Content -Path $k -Value $before[$k] -NoNewline }
        }
        $changed | Should -BeNullOrEmpty -Because "docs must match help comments; run ./src/scripts/Build-Documentation and commit ($($changed -join ', '))"
    }
}
