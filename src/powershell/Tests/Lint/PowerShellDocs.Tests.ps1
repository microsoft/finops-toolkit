BeforeDiscovery {
    $root = (Get-Item -Path $PSScriptRoot).Parent.Parent.Parent.Parent.FullName
    $commands = Get-ChildItem -Path (Join-Path $root 'src/powershell/Public') -Filter '*-FinOps*.ps1' -File |
        ForEach-Object { @{ Name = $_.BaseName } }
}

BeforeAll {
    $root = (Get-Item -Path $PSScriptRoot).Parent.Parent.Parent.Parent.FullName
    $docsPath = Join-Path $root 'docs-mslearn/toolkit/powershell'
}

# Run `./src/scripts/Build-Documentation` to generate missing pages
Describe 'PowerShell command docs' {
    It 'Should have a docs page for <Name>' -ForEach $commands {
        $page = Get-ChildItem -Path $docsPath -Recurse -Filter "$($Name.ToLower()).md" -File
        $page | Should -Not -BeNullOrEmpty -Because "every public command needs a page generated by Build-Documentation"
        @($page).Count | Should -Be 1 -Because "each command should have exactly one docs page"
    }

    It 'Should list <Name> in powershell-commands.md' -ForEach $commands {
        (Get-Content (Join-Path $docsPath 'powershell-commands.md') -Raw) | Should -Match "\[$Name\]"
    }
}
